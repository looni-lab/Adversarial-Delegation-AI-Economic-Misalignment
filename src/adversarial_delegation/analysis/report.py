"""Build the full single-model analytics report from a trace directory.

Produces, under ``out/``: ``metrics.json`` (the computed grid), ``tables/``
(PNG + Markdown + LaTeX), and ``figures/`` (PNG), plus a short ``README.md``.
"""

from __future__ import annotations

import json
from pathlib import Path

from .compute import compute_model
from .figures import render_figures
from .tables import render_tables


def build_report(model: str, model_dir, out) -> dict:
    """Compute metrics for ``model`` and render the full report into ``out``.

    ``model_dir`` is the model's trace tree (``<traces>/<model>`` with per-domain
    subdirectories). Returns the computed metrics dict.
    """
    model_dir, out = Path(model_dir), Path(out)
    out.mkdir(parents=True, exist_ok=True)

    metrics = compute_model(model_dir)
    (out / "metrics.json").write_text(json.dumps({"model": model, **metrics}, indent=2))
    render_tables(model, metrics, out / "tables")
    render_figures(model, metrics, out / "figures")
    _write_readme(model, metrics, out)
    return metrics


def _write_readme(model: str, metrics: dict, out: Path):
    gaps = metrics["gaps"]
    tf = {d: gaps[d].get("tool_full") for d in ("flights", "insurance", "grad_schools")}
    lines = [
        f"# {model} — single-model analytics", "",
        "Generated by `adversarial_delegation.analysis`. All numbers use the "
        "trial-level in-range genuine-inventory gate.", "",
        "## Tool-full discrimination gap", "",
        f"- flights: {tf['flights']}  ·  insurance: {tf['insurance']}  ·  "
        f"grad_schools: {tf['grad_schools']}",
        f"- mean Cohen's d: {metrics['mean_d']}",
        f"- financial-axis retrieval (flights): "
        f"{metrics['financial_retrieval_pct']['flights']}%", "",
        "## Contents", "",
        "- `metrics.json` — the full computed grid",
        "- `tables/` — capability, by_condition, blocking, retrieval (PNG + MD + TeX)",
        "- `figures/` — blocking heatmap, depth ladder, intent override (PNG)",
    ]
    (out / "README.md").write_text("\n".join(lines) + "\n")
